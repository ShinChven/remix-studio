function pickMessages(locale: string): Messages {
  const tag = locale.toLowerCase();
  if (tag.startsWith('zh')) {
    return /(tw|hk|mo|hant)/.test(tag) ? zhTW : zhCN;
  }
  if (tag.startsWith('ja')) return ja;
  if (tag.startsWith('ko')) return ko;
  if (tag.startsWith('fr')) return fr;
  return en;
}

export type Translator = ((key: MessageKey, vars?: Record<string, string | number>) => string) & {
  locale: string;
  /** Translates a status value, falling back to the raw value. */
  status: (value: string) => string;
};

export function createTranslator(locale: string): Translator {
  const messages = pickMessages(locale);
  const translate = ((key: MessageKey, vars?: Record<string, string | number>) =>
    messages[key].replace(/\{(\w+)\}/g, (_, name) => String(vars?.[name] ?? ''))) as Translator;
  translate.locale = locale;
  translate.status = (value: string) => {
    const key = `status_${value}` as MessageKey;
    return key in messages ? messages[key] : value;
  };
  return translate;
}
