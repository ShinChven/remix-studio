function pickLocale(): Strings {
  const lang = (navigator.language || 'en').toLowerCase();
  if (lang.indexOf('zh') === 0) {
    return /tw|hk|mo|hant/.test(lang) ? zhTW : zhCN;
  }
  if (lang.indexOf('ja') === 0) return ja;
  if (lang.indexOf('ko') === 0) return ko;
  if (lang.indexOf('fr') === 0) return fr;
  return en;
}

const strings = pickLocale();

export function countLabel(n: number): string {
  return n === 1 ? t('item') : t('items', { n });
}

export function t(key: keyof Strings, vars?: Record<string, string | number>): string {
  let text = strings[key] || en[key];
  if (vars) {
    for (const name of Object.keys(vars)) text = text.replace(`{${name}}`, String(vars[name]));
  }
  return text;
}
